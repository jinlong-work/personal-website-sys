-- 项目管理：新增项目和图片资源表，为超级管理员、管理员补齐操作权限。
-- 不修改账号与密码；迁移前权限表快照保存在同库私有 schema。
BEGIN;
SET LOCAL search_path TO public;
SET LOCAL lock_timeout = '8s';
SET LOCAL statement_timeout = '60s';
SELECT pg_advisory_xact_lock(536041, 6);

CREATE SCHEMA IF NOT EXISTS website_backup_20261016_projects;
REVOKE ALL ON SCHEMA website_backup_20261016_projects FROM PUBLIC;
CREATE TABLE IF NOT EXISTS website_backup_20261016_projects.migration_info (
    migration_id TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details JSONB NOT NULL DEFAULT '{}'::jsonb
);
REVOKE ALL ON ALL TABLES IN SCHEMA website_backup_20261016_projects FROM PUBLIC;

DO $migration$
BEGIN
    IF EXISTS (SELECT 1 FROM website_backup_20261016_projects.migration_info WHERE migration_id = '006_project_management') THEN
        RETURN;
    END IF;
    IF to_regclass('public.website_project') IS NOT NULL OR to_regclass('public.website_project_asset') IS NOT NULL THEN
        RAISE EXCEPTION 'Project tables already exist without migration marker; refusing to overwrite';
    END IF;
    LOCK TABLE public.sys_menu, public.sys_role_menu IN SHARE ROW EXCLUSIVE MODE;
    CREATE TABLE website_backup_20261016_projects.sys_menu_before AS TABLE public.sys_menu;
    CREATE TABLE website_backup_20261016_projects.sys_role_menu_before AS TABLE public.sys_role_menu;

    CREATE TABLE public.website_project_asset (
        asset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        path VARCHAR(100) NOT NULL UNIQUE CHECK (path ~ '^/files/projects/[a-f0-9]{32}\.jpg$'),
        original_name VARCHAR(200) NOT NULL DEFAULT '',
        width INTEGER NOT NULL CHECK (width BETWEEN 1 AND 2560),
        height INTEGER NOT NULL CHECK (height BETWEEN 1 AND 2560),
        file_size BIGINT NOT NULL CHECK (file_size BETWEEN 1 AND 10485760),
        create_by VARCHAR(100) NOT NULL DEFAULT '',
        create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE TABLE public.website_project (
        project_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name VARCHAR(150) NOT NULL CHECK (char_length(btrim(name)) > 0),
        project_type VARCHAR(80) NOT NULL CHECK (char_length(btrim(project_type)) > 0),
        description TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 12000),
        category VARCHAR(100) NOT NULL DEFAULT '',
        headline VARCHAR(180) NOT NULL DEFAULT '',
        summary VARCHAR(1000) NOT NULL DEFAULT '',
        technologies JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(technologies) = 'array' AND jsonb_array_length(technologies) <= 20),
        achievements JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(achievements) = 'array' AND jsonb_array_length(achievements) <= 30),
        images JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(images) = 'array' AND jsonb_array_length(images) <= 12),
        english JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(english) = 'object'),
        featured BOOLEAN NOT NULL DEFAULT TRUE,
        status VARCHAR(12) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
        sort_order INTEGER NOT NULL DEFAULT 100 CHECK (sort_order BETWEEN 0 AND 999999),
        version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
        del_flag CHAR(1) NOT NULL DEFAULT '0' CHECK (del_flag IN ('0', '2')),
        create_by VARCHAR(100) NOT NULL DEFAULT '',
        create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        update_by VARCHAR(100) NOT NULL DEFAULT '',
        update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        CONSTRAINT ck_project_publication CHECK (status <> 'published' OR (char_length(btrim(description)) > 0 AND jsonb_array_length(images) > 0))
    );
    CREATE INDEX idx_website_project_public ON public.website_project (status, sort_order, project_id) WHERE del_flag = '0';
    CREATE INDEX idx_website_project_assets_created ON public.website_project_asset (create_time DESC);
    COMMENT ON TABLE public.website_project IS '首页项目内容、展示排序及发布状态；images第一张为封面';
    COMMENT ON TABLE public.website_project_asset IS 'MinIO项目效果图元数据；替换和移除引用时保留图片对象';

    INSERT INTO public.sys_menu (menu_name, parent_id, order_num, path, menu_type, visible, status, perms, create_by, remark)
    SELECT permission.name, 0, permission.position, '', 'F', '1', '0', permission.key, 'migration:006', '个人网站项目管理操作权限'
    FROM (VALUES
        (20, '项目查询', 'website:project:list'),
        (21, '新增项目', 'website:project:add'),
        (22, '编辑项目', 'website:project:edit'),
        (23, '删除项目', 'website:project:remove'),
        (24, '发布下架项目', 'website:project:publish'),
        (25, '上传项目效果图', 'website:project:upload')
    ) AS permission(position, name, key)
    WHERE NOT EXISTS (SELECT 1 FROM public.sys_menu m WHERE m.perms = permission.key);

    INSERT INTO public.sys_role_menu (role_id, menu_id)
    SELECT r.role_id, m.menu_id FROM public.sys_role r CROSS JOIN public.sys_menu m
    WHERE r.role_key IN ('admin', 'manager') AND r.status = '0' AND r.del_flag = '0'
      AND m.perms IN ('website:project:list', 'website:project:add', 'website:project:edit',
                      'website:project:remove', 'website:project:publish', 'website:project:upload')
    ON CONFLICT DO NOTHING;

    INSERT INTO website_backup_20261016_projects.migration_info(migration_id, details)
    VALUES ('006_project_management', '{"schemaApplied":true,"seeded":false}'::jsonb);
    REVOKE ALL ON ALL TABLES IN SCHEMA website_backup_20261016_projects FROM PUBLIC;
END
$migration$;
COMMIT;
