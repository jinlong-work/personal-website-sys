-- 保留旧账号角色关系，不改动密码；使用角色标识查找ID，避免假定已有role_id。
DO $$
BEGIN
    IF current_setting('personal_website.migrating_legacy', true) = 'true' THEN
        INSERT INTO sys_user_role (user_id, role_id)
        SELECT u.user_id, r.role_id FROM sys_user u JOIN sys_role r
            ON r.role_key = CASE u.role WHEN 'ADMIN' THEN 'admin' ELSE 'common' END
        ON CONFLICT DO NOTHING;
    END IF;
END;
$$;

