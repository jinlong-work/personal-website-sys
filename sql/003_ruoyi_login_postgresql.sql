-- PostgreSQL：若依登录所需的表与配置（新数据库与原001脚本建的用户表均可执行）。
-- 手动在业务数据库执行；应用不会自动执行此脚本。建议先备份旧账号表。
-- 不删除表，不覆盖已有账号密码，不导入若依演示账号或无对应前端页面的菜单。
BEGIN;
SET LOCAL search_path TO public;

-- 将本项目旧版 sys_user 的字段迁移为若依命名，保留ID与BCrypt哈希。
DO $$
BEGIN
    IF to_regclass('public.sys_user') IS NOT NULL
       AND EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='sys_user' AND column_name='username')
       AND NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='sys_user' AND column_name='user_name') THEN
        -- 若依将用户ID=1作为超级管理员，不能将旧普通用户静默升级。
        IF EXISTS (SELECT 1 FROM public.sys_user WHERE id=1 AND role <> 'ADMIN') THEN
            RAISE EXCEPTION '旧表ID=1不是ADMIN；请先人工核实账号权限与ID，再执行迁移';
        END IF;
        DROP TRIGGER IF EXISTS trg_sys_user_updated_at ON public.sys_user;
        ALTER TABLE public.sys_user DROP CONSTRAINT IF EXISTS ck_sys_user_status;
        ALTER TABLE public.sys_user RENAME COLUMN id TO user_id;
        ALTER TABLE public.sys_user RENAME COLUMN username TO user_name;
        ALTER TABLE public.sys_user RENAME COLUMN password_hash TO password;
        ALTER TABLE public.sys_user RENAME COLUMN nickname TO nick_name;
        ALTER TABLE public.sys_user RENAME COLUMN last_login_at TO login_date;
        ALTER TABLE public.sys_user RENAME COLUMN created_at TO create_time;
        ALTER TABLE public.sys_user RENAME COLUMN updated_at TO update_time;
        ALTER TABLE public.sys_user ALTER COLUMN status SET DEFAULT '0';
        UPDATE public.sys_user SET status = CASE status WHEN 'ACTIVE' THEN '0' ELSE '1' END;
        PERFORM set_config('personal_website.migrating_legacy', 'true', true);
        -- 旧role字段暂时保留，稍后转换为sys_user_role关系。
    END IF;
END;
$$;

CREATE TABLE IF NOT EXISTS sys_dept (
    dept_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT NOT NULL DEFAULT 0,
    ancestors VARCHAR(500) NOT NULL DEFAULT '0',
    dept_name VARCHAR(100) NOT NULL DEFAULT '',
    order_num INTEGER NOT NULL DEFAULT 0,
    leader VARCHAR(100), phone VARCHAR(30), email VARCHAR(254),
    status CHAR(1) NOT NULL DEFAULT '0', del_flag CHAR(1) NOT NULL DEFAULT '0',
    create_by VARCHAR(100) DEFAULT '', create_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(100) DEFAULT '', update_time TIMESTAMPTZ, remark VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS sys_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dept_id BIGINT,
    user_name VARCHAR(100) NOT NULL,
    nick_name VARCHAR(100) NOT NULL DEFAULT '',
    user_type VARCHAR(2) NOT NULL DEFAULT '00',
    email VARCHAR(254) DEFAULT '', phonenumber VARCHAR(30) DEFAULT '',
    sex CHAR(1) DEFAULT '2', avatar VARCHAR(500) DEFAULT '',
    password VARCHAR(255) NOT NULL,
    status CHAR(1) NOT NULL DEFAULT '0', del_flag CHAR(1) NOT NULL DEFAULT '0',
    login_ip VARCHAR(128) DEFAULT '', login_date TIMESTAMPTZ, pwd_update_date TIMESTAMPTZ,
    create_by VARCHAR(100) DEFAULT '', create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(100) DEFAULT '', update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    remark VARCHAR(500)
);

