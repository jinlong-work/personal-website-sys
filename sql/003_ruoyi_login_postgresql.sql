CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_user_name_lower ON sys_user (LOWER(user_name));

CREATE OR REPLACE FUNCTION public.sys_user_set_update_time() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    NEW.update_time := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS trg_sys_user_update_time ON sys_user;
CREATE TRIGGER trg_sys_user_update_time BEFORE UPDATE ON sys_user
FOR EACH ROW EXECUTE FUNCTION public.sys_user_set_update_time();

CREATE TABLE IF NOT EXISTS sys_role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(100) NOT NULL, role_key VARCHAR(100) NOT NULL UNIQUE,
    role_sort INTEGER NOT NULL DEFAULT 0, data_scope CHAR(1) DEFAULT '1',
    menu_check_strictly BOOLEAN NOT NULL DEFAULT TRUE, dept_check_strictly BOOLEAN NOT NULL DEFAULT TRUE,
    status CHAR(1) NOT NULL DEFAULT '0', del_flag CHAR(1) NOT NULL DEFAULT '0',
    create_by VARCHAR(100) DEFAULT '', create_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(100) DEFAULT '', update_time TIMESTAMPTZ, remark VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS sys_menu (
    menu_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_name VARCHAR(100) NOT NULL, parent_id BIGINT NOT NULL DEFAULT 0,
    order_num INTEGER NOT NULL DEFAULT 0, path VARCHAR(255) DEFAULT '',
    component VARCHAR(255), "query" VARCHAR(255), route_name VARCHAR(100) DEFAULT '',
    is_frame CHAR(1) NOT NULL DEFAULT '1', is_cache CHAR(1) NOT NULL DEFAULT '0',
    menu_type CHAR(1) NOT NULL, visible CHAR(1) NOT NULL DEFAULT '0', status CHAR(1) NOT NULL DEFAULT '0',
    perms VARCHAR(255), icon VARCHAR(100) DEFAULT '#',
    create_by VARCHAR(100) DEFAULT '', create_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(100) DEFAULT '', update_time TIMESTAMPTZ, remark VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS sys_user_role (
    user_id BIGINT NOT NULL REFERENCES sys_user(user_id),
    role_id BIGINT NOT NULL REFERENCES sys_role(role_id),
    PRIMARY KEY (user_id, role_id)
);
CREATE TABLE IF NOT EXISTS sys_role_menu (
    role_id BIGINT NOT NULL REFERENCES sys_role(role_id),
    menu_id BIGINT NOT NULL REFERENCES sys_menu(menu_id),
    PRIMARY KEY (role_id, menu_id)
);
CREATE INDEX IF NOT EXISTS idx_sys_user_role_role ON sys_user_role(role_id);
CREATE INDEX IF NOT EXISTS idx_sys_role_menu_menu ON sys_role_menu(menu_id);

CREATE TABLE IF NOT EXISTS sys_config (
    config_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_name VARCHAR(100) DEFAULT '', config_key VARCHAR(100) NOT NULL UNIQUE,
    config_value VARCHAR(500) NOT NULL DEFAULT '', config_type CHAR(1) NOT NULL DEFAULT 'Y',
    create_by VARCHAR(100) DEFAULT '', create_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    update_by VARCHAR(100) DEFAULT '', update_time TIMESTAMPTZ, remark VARCHAR(500)
);

CREATE TABLE IF NOT EXISTS sys_logininfor (
    info_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_name VARCHAR(100) DEFAULT '', ipaddr VARCHAR(128) DEFAULT '',
    login_location VARCHAR(255) DEFAULT '', browser VARCHAR(100) DEFAULT '', os VARCHAR(100) DEFAULT '',
    status CHAR(1) DEFAULT '0', msg VARCHAR(500) DEFAULT '', login_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_sys_logininfor_login_time ON sys_logininfor(login_time DESC);

